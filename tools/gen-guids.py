#!/usr/bin/env python3
"""Generates src/guid_names.rs from the edk2 package declarations in tools/dec.

Each .dec file names its GUIDs as
    gEfiSimpleFileSystemProtocolGuid = { 0x964E5B22, 0x6459, 0x11D2, { 0x8E, ... }}
and the table maps the GUID back to that name (without the g...Guid wrapping),
so weefy can show a name beside the GUIDs it finds on a machine.

Usage: tools/gen-guids.py [--dec-dir DIR] [--out FILE]
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
# Earlier packages win when two of them name the same GUID.
ORDER = ["MdePkg", "MdeModulePkg", "SecurityPkg", "NetworkPkg", "ShellPkg"]

ENTRY = re.compile(
    r"^\s*(g\w+)\s*=\s*\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,"
    r"\s*\{\s*((?:0x[0-9a-fA-F]+\s*,\s*){7}0x[0-9a-fA-F]+)\s*\}\s*\}",
    re.M,
)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dec-dir", default=str(ROOT / "tools" / "dec"))
    ap.add_argument("--out", default=str(ROOT / "src" / "guid_names.rs"))
    args = ap.parse_args()

    decs = sorted(
        pathlib.Path(args.dec_dir).glob("*.dec"),
        key=lambda p: (ORDER.index(p.stem) if p.stem in ORDER else len(ORDER), p.stem),
    )
    if not decs:
        sys.exit(f"no .dec files in {args.dec_dir}")

    seen = {}
    for dec in decs:
        for m in ENTRY.finditer(dec.read_text(errors="replace")):
            name, a, b, c, rest = m.groups()
            d = [int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", rest)]
            guid = "%08x-%04x-%04x-%02x%02x-%s" % (
                int(a, 16), int(b, 16), int(c, 16), d[0], d[1],
                "".join("%02x" % x for x in d[2:]),
            )
            name = re.sub(r"^g", "", name)
            name = re.sub(r"Guid$", "", name)
            seen.setdefault(guid, (name, dec.stem))

    lines = [
        "// Generated by tools/gen-guids.py from the edk2 package declarations in",
        "// tools/dec. Do not edit; rerun the script.",
        "",
        "use uefi::{Guid, guid};",
        "",
        "/// GUID, the name edk2 gives it, and the package that declares it.",
        "pub static NAMES: &[(Guid, &str, &str)] = &[",
    ]
    for guid in sorted(seen):
        name, pkg = seen[guid]
        lines.append(f'    (guid!("{guid}"), "{name}", "{pkg}"),')
    lines.append("];")
    pathlib.Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"{args.out}: {len(seen)} GUIDs from {len(decs)} packages")


if __name__ == "__main__":
    main()
